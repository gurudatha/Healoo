#!/usr/bin/env python3
"""Writes Server/THIRD-PARTY-LICENSES.txt: every Rust library the server depends on, with the
licence it declares and the licence, copyright and notice files shipped in its package.
Identical texts are printed once and list the libraries that use them.

Run it again after changing Cargo.toml. Two steps, from the Server folder (PowerShell or bash);
both containers share the Cargo registry volume, where the packages' files are:

  docker run --rm -v "${PWD}:/srv:ro" -v healoo-cargo-reg:/usr/local/cargo/registry -v healoo-meta:/meta rust:1.94-slim \
    sh -c "mkdir /w && cp -r /srv/care-api /srv/config /w/ && cd /w/care-api && cargo metadata --format-version 1 > /meta/meta.json"

  docker run --rm -v "${PWD}:/srv" -v healoo-cargo-reg:/usr/local/cargo/registry:ro -v healoo-meta:/meta:ro python:3.12-alpine \
    python /srv/tools/third_party_licenses.py /meta/meta.json /srv/THIRD-PARTY-LICENSES.txt

Uses only the Python standard library.
"""
import hashlib
import json
import os
import re
import sys

PATTERN = re.compile(r"^(licen[sc]e|copying|notice|unlicense|copyright)|_licen[sc]e", re.IGNORECASE)
SKIP_EXT = (".rs", ".html", ".png", ".svg")


def licence_files(folder):
    """Licence-like files in the package folder and one level below (e.g. bundled fonts)."""
    found = []
    for base, dirs, files in os.walk(folder):
        depth = os.path.relpath(base, folder).count(os.sep) + (0 if base == folder else 1)
        if depth >= 1:
            dirs[:] = []            # look one level down, no further
        dirs[:] = [d for d in dirs if d not in ("target", ".git")]
        for name in files:
            if PATTERN.search(name) and not name.lower().endswith(SKIP_EXT):
                found.append(os.path.join(base, name))
    return sorted(found)


def main(meta_path, out_path):
    with open(meta_path, encoding="utf-8") as f:
        meta = json.load(f)
    packages = sorted((p for p in meta["packages"] if p.get("source")), key=lambda p: (p["name"].lower(), p["version"]))

    texts = {}          # hash -> text
    users = {}          # hash -> ["name version  (file)"]
    without_file = []
    for p in packages:
        folder = os.path.dirname(p["manifest_path"])
        files = licence_files(folder)
        if not files:
            without_file.append(p)
        for path in files:
            with open(path, "rb") as f:
                raw = f.read()
            # Plain text only: no carriage returns or stray control characters.
            text = "".join(c for c in raw.decode("utf-8", "replace").replace("\r", "") if c in "\n\t" or ord(c) >= 32).strip("\n")
            key = hashlib.sha256(text.encode("utf-8")).hexdigest()
            texts.setdefault(key, text)
            users.setdefault(key, []).append(f"{p['name']} {p['version']}  ({os.path.relpath(path, folder).replace(os.sep, '/')})")

    out = []
    w = out.append
    w("Healoo server (care-api): third-party Rust libraries")
    w("=====================================================")
    w("")
    w("Generated by Server/tools/third_party_licenses.py from the packages Cargo resolves for")
    w("Server/care-api. Do not edit by hand; run the script again after changing dependencies.")
    w("")
    w("The list covers every platform Cargo knows about, so it includes libraries that are not")
    w("compiled into the Linux server (for example Windows-only ones).")
    w('Where a library offers a choice of licences ("MIT OR Apache-2.0"), Healoo uses it under the')
    w("MIT licence, or else the first permissive one listed.")
    w("")
    w(f"Libraries: {len(packages)}")
    w("")
    w("PART 1 - LIBRARIES AND THEIR LICENCES")
    w("-------------------------------------")
    w("")
    for p in packages:
        w(f"{p['name']} {p['version']}")
        w(f"    Licence: {p.get('license') or 'see the licence file in the package'}")
        w(f"    Source:  {p.get('repository') or '-'}")
    w("")
    if without_file:
        w("Packages that ship no licence file (the licence above is what the package declares):")
        for p in without_file:
            w(f"    {p['name']} {p['version']} ({p.get('license') or 'not declared'})")
        w("")
    w("PART 2 - LICENCE, COPYRIGHT AND NOTICE TEXTS")
    w("--------------------------------------------")
    w("")
    w("Each text is printed once, preceded by the libraries (and file names) it comes from.")
    # Most widely shared texts first (the common Apache-2.0 and MIT texts), then by first user.
    for key in sorted(texts, key=lambda k: (-len(users[k]), users[k][0].lower())):
        w("")
        w("=" * 80)
        w("Used by:")
        for u in users[key]:
            w(f"    {u}")
        w("-" * 80)
        w(texts[key])
        w("")

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {out_path}: {len(packages)} libraries, {len(texts)} distinct texts, "
          f"{os.path.getsize(out_path)} bytes; {len(without_file)} packages ship no licence file", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: third_party_licenses.py <cargo-metadata.json> <output.txt>")
    main(sys.argv[1], sys.argv[2])
